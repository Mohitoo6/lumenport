import { writeFileSync } from 'node:fs';
import { CHIEF_SECRETARY, MINISTER_BY_ID } from '../../src/game/council/ministries';
import type { CalibrationRecord, LineRecord, MeetingRecord } from './council.eval';
import type { Verdict } from './judge';
import { lettersIn } from './grade';

/** Turns an evaluation run into eval/REPORT.md. */

interface Run {
  stamp: string;
  providers: string[];
  judgeModel: string;
  unavailable: string[];
  meetings: MeetingRecord[];
  calibration: CalibrationRecord;
}

const pct = (a: number, b: number): string => (b === 0 ? 'n/a' : `${Math.round((100 * a) / b)}% (${a}/${b})`);
const mean = (xs: number[]): string => (xs.length ? (xs.reduce((s, x) => s + x, 0) / xs.length).toFixed(2) : 'n/a');
const who = (id: string): string => (id === 'chief' ? `${CHIEF_SECRETARY.name} (Chief Secretary)` : `${MINISTER_BY_ID[id as keyof typeof MINISTER_BY_ID]?.name} (${MINISTER_BY_ID[id as keyof typeof MINISTER_BY_ID]?.short})`);
const quote = (s: string, n = 260): string => `“${s.length > n ? s.slice(0, n - 1) + '…' : s}”`;

/** The option(s) most ministers backed at the end. */
function plurality(m: MeetingRecord): string[] {
  const count = new Map<string, number>();
  for (const o of Object.values(m.final)) count.set(o, (count.get(o) ?? 0) + 1);
  const top = Math.max(0, ...count.values());
  return [...count].filter(([, n]) => n === top && top > 0).map(([o]) => o);
}

export function writeReport(run: Run, path: string): void {
  const { meetings, calibration } = run;
  const lines: Array<{ m: MeetingRecord; l: LineRecord }> = meetings.flatMap((m) => m.lines.map((l) => ({ m, l })));
  const ministerLines = lines.filter(({ l }) => l.minister !== 'chief');
  const out: string[] = [];
  const p = (s = ''): void => {
    out.push(s);
  };

  p('# AI council evaluation');
  p();
  p(`Run ${run.stamp} (UTC). Ministers spoke through ${run.providers.join(' → ')}; the judge was ${run.judgeModel}.${run.unavailable.length ? ` Not available during the run: ${run.unavailable.join('; ')}.` : ''} Generated by \`tests/eval/council.eval.ts\`; raw transcripts and every score are in \`eval/runs/council-${run.stamp}.json\`.`);
  p();
  p('**Question:** do the AI ministers argue about the actual problem from the game’s real data, or do they just produce plausible-sounding text?');
  p();
  p('**Method.** Three independent kinds of evidence:');
  p('1. *Deterministic checks* (code, no AI): every number a minister says is looked up in the exact prompt that minister received; option letters must exist; Hindi meetings must be in Devanagari; length rules.');
  p('2. *Behavioural tests*: a controlled experiment where one fact is changed and everything else is held fixed, and a meeting under the mayor’s explicit constraints. If the model were only generating plausible text, positions would not move with the data.');
  p('3. *LLM-as-judge*: a different model scores every statement 1–5 for grounding, relevance, staying in role and reasoning, with the same evidence the ministers had. The judge is itself tested with planted bad statements.');
  p();

  // Overview
  const done = meetings.filter((m) => m.decision && m.lines.length > 0);
  p('## Overview');
  p();
  p('| Meetings | Completed | Statements | Silent turns | Failed turns | Mean duration |');
  p('|---|---|---|---|---|---|');
  p(`| ${meetings.length} | ${done.length} | ${ministerLines.length} + ${meetings.filter((m) => m.decision).length} chair summaries | ${meetings.reduce((s, m) => s + m.silent.length, 0)} | ${meetings.reduce((s, m) => s + m.failed.length, 0)} | ${mean(meetings.map((m) => m.seconds))} s |`);
  p();
  p('| Meeting | Attending | Spoke | Recommended | Most backed | Duration |');
  p('|---|---|---|---|---|---|');
  for (const m of meetings) {
    const spoke = new Set(m.lines.filter((l) => l.minister !== 'chief').map((l) => l.minister)).size;
    p(`| ${m.name} | ${m.seats.length} | ${spoke} | ${m.decision?.option ?? '—'} | ${plurality(m).join(', ') || '—'} | ${m.seconds} s |`);
  }
  p();

  // Deterministic
  const checked = lines.filter(({ l }) => l.checks);
  const nums = checked.reduce((s, { l }) => s + l.checks!.numbers.checked, 0);
  const bad = checked.filter(({ l }) => l.checks!.numbers.ungrounded.length > 0);
  const badNums = bad.reduce((s, { l }) => s + l.checks!.numbers.ungrounded.length, 0);
  const en = checked.filter(({ m }) => m.lang === 'en');
  const hi = checked.filter(({ m }) => m.lang === 'hi');
  p('## 1. Deterministic checks');
  p();
  p('| Check | Result |');
  p('|---|---|');
  p(`| Option letter exists | ${pct(checked.filter(({ l }) => l.checks!.validOption).length, checked.length)} |`);
  p(`| Text and “option” field agree | ${pct(checked.filter(({ l }) => l.checks!.namesItsChoice).length, checked.length)} |`);
  p(`| Numbers found in what the speaker was shown | ${pct(nums - badNums, nums)} of figures quoted |`);
  p(`| Statements with any unverified number | ${pct(bad.length, checked.length)} |`);
  p(`| Length within the rule (1–5 sentences) | ${pct(checked.filter(({ l }) => l.checks!.lengthOk).length, checked.length)} |`);
  p(`| English meetings in English | ${pct(en.filter(({ l }) => l.checks!.languageOk).length, en.length)} |`);
  p(`| Hindi meeting in Devanagari | ${pct(hi.filter(({ l }) => l.checks!.languageOk).length, hi.length)} |`);
  p();
  if (bad.length) {
    p('Numbers the check could not find in the prompt (each needs a human look: some are legitimate arithmetic, some are invented):');
    p();
    for (const { m, l } of bad) p(`- ${m.name}, ${who(l.minister)} r${l.round}: **${l.checks!.numbers.ungrounded.join(', ')}** in ${quote(l.text)}`);
    p();
  }

  // Behaviour: constraint
  p('## 2. Behavioural tests');
  p();
  const con = meetings.find((m) => m.group === 'constraint');
  if (con) {
    const feasible = con.options.filter((o) => o.displacedHomes === 0 && o.jobsLost === 0 && o.cost <= 1500);
    const rec = con.options.find((o) => o.id === con.decision?.option);
    const ok = !!rec && feasible.some((o) => o.id === rec.id);
    p('### Mayor’s constraints');
    p();
    p(`Instruction: “${con.note}”`);
    p();
    p(`Options that satisfy it: ${feasible.map((o) => `${o.id} (${o.title})`).join('; ') || 'none'}.`);
    p();
    p(`Recommended: **${rec ? `${rec.id} (${rec.title}, $${rec.cost}, ${rec.displacedHomes} homes / ${rec.jobsLost} jobs displaced)` : '—'}** → ${ok ? '**respects the constraints**' : '**violates the constraints**'}.`);
    const base = meetings.find((m) => m.group === 'issue' && m.issue.kind === con.issue.kind);
    if (base) p(`Same issue without the instruction recommended: ${base.decision?.option ?? '—'}.`);
    p();
  }

  // Behaviour: counterfactual
  const cf = meetings.filter((m) => m.group === 'counterfactual');
  if (cf.length) {
    p('### Controlled experiment: one fact changed');
    p();
    p('Same issue, same options, same ministers in the room. Only option A’s demolition fact differs: *no buildings demolished* vs *40 homes (1,380 residents) and 6 workplaces demolished*. Two meetings per variant.');
    p();
    p('| Run | Ministers backing A at the end | Statements objecting to A | Mentions of homes/residents | Chair recommends |');
    p('|---|---|---|---|---|');
    const stats = cf.map((m) => {
      const backA = Object.values(m.final).filter((o) => o === 'A').length;
      const objectA = m.lines.filter((l) => l.minister !== 'chief' && (l.stance === 'oppose' || l.stance === 'concern') && l.option !== 'A' && lettersIn(l.text, ['A', 'B', 'C', 'D', 'E']).includes('A')).length;
      const homes = m.lines.filter((l) => /\bhomes?\b|residents|displac|demoli/i.test(l.text)).length;
      p(`| ${m.name} | ${backA} of ${Object.keys(m.final).length} | ${objectA} | ${homes} | ${m.decision?.option ?? '—'} |`);
      return { variant: m.variant, backA, objectA, chiefA: m.decision?.option === 'A' };
    });
    const sum = (v: string, k: 'backA' | 'objectA'): number => stats.filter((s) => s.variant === v).reduce((t, s) => t + s[k], 0);
    const chief = (v: string): string => `${stats.filter((s) => s.variant === v && s.chiefA).length}/${stats.filter((s) => s.variant === v).length}`;
    p();
    p(`Totals — backing A: ${sum('clean', 'backA')} (no demolition) vs ${sum('harsh', 'backA')} (40 homes). Objections to A: ${sum('clean', 'objectA')} vs ${sum('harsh', 'objectA')}. Chair picked A: ${chief('clean')} vs ${chief('harsh')}.`);
    p();
  }

  // Judge
  const verdicts: Array<{ m: MeetingRecord; v: Verdict }> = meetings.flatMap((m) => (m.judge?.verdicts ?? []).map((v) => ({ m, v })));
  p('## 3. LLM-as-judge');
  p();
  const judges = [...new Set(meetings.map((m) => m.judge?.provider).filter(Boolean))];
  p(`Judge: ${judges.join(', ') || 'unavailable'}. Scored ${verdicts.length} of ${lines.length} statements.${meetings.some((m) => m.judge?.error) ? ` Not judged (provider errors): ${meetings.filter((m) => m.judge?.error).map((m) => m.name).join('; ')}.` : ''}`);
  p();
  p('| Criterion | Mean (1–5) | Scored 4 or 5 |');
  p('|---|---|---|');
  for (const k of ['grounded', 'on_topic', 'in_role', 'reasoning'] as const) {
    const xs = verdicts.map(({ v }) => v[k]).filter((x) => Number.isFinite(x));
    p(`| ${k} | ${mean(xs)} | ${pct(xs.filter((x) => x >= 4).length, xs.length)} |`);
  }
  p();
  const flagged = verdicts.filter(({ v }) => v.unsupported.length > 0);
  if (flagged.length) {
    p(`Claims the judge could not find in the evidence (${flagged.length} statements):`);
    p();
    for (const { m, v } of flagged.slice(0, 20)) {
      const l = m.lines.find((x) => x.id === v.id);
      p(`- ${m.name}, ${l ? who(l.minister) : v.id}: ${v.unsupported.map((u) => quote(u, 140)).join('; ')}`);
    }
    p();
  }

  // Chair
  p('### The chair');
  p();
  let agree = 0;
  let split = 0;
  let dissent = 0;
  for (const m of done) {
    const top = plurality(m);
    if (top.includes(m.decision!.option)) agree++;
    if (new Set(Object.values(m.final)).size > 1) {
      split++;
      if (m.decision!.dissent.trim()) dissent++;
    }
  }
  p(`- Recommendation matches the option most ministers backed: ${pct(agree, done.length)}.`);
  p(`- When ministers ended split, the dissent was recorded: ${pct(dissent, split)}.`);
  p();

  // Calibration
  p('## 4. Is the judge trustworthy? Planted statements');
  p();
  p('Three fabricated statements were slipped into a real transcript before judging. A useful judge must score them low; the deterministic check must flag invented numbers.');
  p();
  p('| Planted | grounded | on_topic | in_role | Caught by judge | Caught by number check |');
  p('|---|---|---|---|---|---|');
  const cv = new Map((calibration.judge?.verdicts ?? []).map((v) => [v.id, v]));
  for (const pl of calibration.planted) {
    const v = cv.get(pl.id);
    const caught = v ? (pl.kind === 'invented-numbers' ? v.grounded <= 2 : pl.kind === 'off-topic' ? v.on_topic <= 2 : v.in_role <= 2) : false;
    const numCaught = (calibration.checks[pl.id]?.numbers.ungrounded.length ?? 0) > 0;
    p(`| ${pl.kind}: ${quote(pl.text, 90)} | ${v?.grounded ?? '—'} | ${v?.on_topic ?? '—'} | ${v?.in_role ?? '—'} | ${v ? (caught ? 'yes' : 'no') : 'not scored'} | ${pl.kind === 'invented-numbers' ? (numCaught ? 'yes' : 'no') : 'n/a'} |`);
  }
  const realInCal = (calibration.judge?.verdicts ?? []).filter((v) => !v.id.startsWith('planted'));
  p();
  p(`Real statements in the same judging call averaged grounded ${mean(realInCal.map((v) => v.grounded))}, on_topic ${mean(realInCal.map((v) => v.on_topic))}, in_role ${mean(realInCal.map((v) => v.in_role))}.`);
  p();

  // Excerpts
  p('## Excerpts');
  p();
  for (const m of meetings.filter((x) => x.group !== 'counterfactual').slice(0, 4)) {
    p(`**${m.name}** — ${m.issue.title}`);
    p();
    for (const l of m.lines.slice(0, 3)) p(`- ${who(l.minister)}, round ${l.round}, backs ${l.option}: ${quote(l.text, 400)}`);
    const c = m.lines.find((l) => l.minister === 'chief');
    if (c) p(`- Chair recommends ${c.option}: ${quote(c.text, 400)}`);
    p();
  }

  p('## Limits of this evaluation');
  p();
  p('- One scripted town and one run per scenario (two per counterfactual variant): free-tier rate limits make large samples slow. Results show behaviour, not a statistically tight rate.');
  p('- The number check is conservative: it flags arithmetic it cannot reproduce (for example a percentage computed by the minister), so every flag is listed for a human to read.');
  p('- The judge is a language model too; section 4 measures whether it catches known-bad statements, but it can still miss subtler errors.');
  p('- Whether a recommendation is the *best* policy is a value judgement; these tests check that it is grounded, consistent and responsive to data and instructions.');
  writeFileSync(path, out.join('\n') + '\n');
}
